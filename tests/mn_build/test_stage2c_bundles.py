@pytest.mark.parametrize("module",[initial,reactive])
def test_failed_pf_is_diagnostic_only(source_paths,tmp_path,monkeypatch,module):
    p=replace(source_paths,output_dir=tmp_path/"generated")
    failed={"status":"AC_PF_NOT_CONVERGED","exception":None,"subnetworks":[],"warnings":["injected"]}
    monkeypatch.setattr(module,"execute_pf",lambda *a,**kw:failed)
    with pytest.raises(inputs.ScenarioFailure):module.regenerate_for_verification(p,p.output_dir/"scenario")
    assert not (p.output_dir/"scenario").exists()
    diagnostic=p.output_dir/"scenario.failed"
    assert {f.name for f in diagnostic.iterdir()}=={"failure.json"}
    data=json.loads((diagnostic/"failure.json").read_text())
    assert data["accepted"] is False and data["status"]=="FAILED_NOT_A_MODEL"


