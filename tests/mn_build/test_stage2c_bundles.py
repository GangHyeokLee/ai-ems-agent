@pytest.mark.parametrize("kind", ["initial", "reactive"])
def test_reference_and_migration_actual_bundles(source_paths, tmp_path, reference_modules, kind, monkeypatch):
    """Execute original orchestration against copied writable outputs, not sources."""
    root = tmp_path/"reference"
    root.mkdir()
    config, settings = inputs.read_settings(source_paths)
    # Original ROOT semantics are reproduced in a private project. Read-only
    # model inputs are copied too, so original replacing exporters cannot follow
    # an output symlink into the real Earth checkout.
    for logical in inputs.contract()["files"]:
        target=root/logical
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(logical_input(source_paths, logical), target)
    for name in ("run_mn35k_acpf", "run_mn35k_reactive_support"):
        monkeypatch.setattr(reference_modules[name], "ROOT", root)
    if kind == "initial":
        module=reference_modules["run_mn35k_acpf"]
        monkeypatch.setattr(sys, "argv", ["reference", "--config", str(root/"configs/mn35k_acpf.json")])
        assert module.main() == 0
        ref_reports=root/"reports/power_flow"
        ref_model=root/config["output_model"]
        migrated=initial
    else:
        module=reference_modules["run_mn35k_reactive_support"]
        # Avoid the source's matching-output replacement policy: new output only.
        (root/settings["output_model"]).unlink()
        assert module.run(root/"configs/mn35k_reactive_support.json") == 0
        ref_reports=root/settings["reports_dir"]
        ref_model=root/settings["output_model"]
        migrated=reactive
    paths=replace(source_paths, output_dir=tmp_path/"generated")
    result=migrated.regenerate_for_verification(paths,paths.output_dir/kind)
    target=Path(result["artifact"])
    assert sha256(ref_model) == sha256(target/ref_model.name)
    # All original reports generated by this invocation, not test_results.txt.
    for name in migrated.EXPECTED_FILES:
        if name == ref_model.name:
            continue
        candidate=target/name
        reference=ref_reports/name
        if name == "source_preservation.json":
            # The migrated manifest intentionally protects more artifacts than
            # the original; pins and unchanged=true are asserted independently.
            assert json.loads(candidate.read_text())["unchanged"]
        else:
            assert candidate.read_bytes() == reference.read_bytes(), name
    first_hash=sha256(target/ref_model.name)
    # A second complete computation has deterministic model/report bytes.
    again=migrated.regenerate_for_verification(paths,paths.output_dir/(kind+"-again"))
    other=Path(again["artifact"])
    for file in target.iterdir():
        assert file.read_bytes() == (other/file.name).read_bytes(), file.name
    with pytest.raises(ValueError,match="existing artifact"):
        migrated.regenerate_for_verification(paths,target)
    assert sha256(target/ref_model.name)==first_hash
    historical=pypsa.Network(logical_input(source_paths, config["output_model"] if kind=="initial" else settings["output_model"]))
    regenerated=pypsa.Network(target/ref_model.name)
    compare_networks(historical,regenerated)
    historical_path=logical_input(source_paths,config["output_model"] if kind=="initial" else settings["output_model"])
    with xr.open_dataset(historical_path) as left, xr.open_dataset(target/ref_model.name) as right:
        xr.testing.assert_identical(left,right)
    report = {
        "kind": kind, "original_model_sha256": sha256(ref_model),
        "migrated_model_sha256": sha256(target/ref_model.name),
        "historical_model_sha256": sha256(logical_input(source_paths, config["output_model"] if kind=="initial" else settings["output_model"])),
        "exact_static_dynamic_metadata_ybus": True,
        "reports": {name: {"original": sha256(ref_reports/name), "migrated": sha256(target/name),
                            "equal": sha256(ref_reports/name)==sha256(target/name),
                            "historical": sha256(source_paths.source_project/("reports/power_flow" if kind=="initial" else "reports/reactive_support")/name)}
                    for name in migrated.EXPECTED_FILES if name != ref_model.name},
        "source_code_sha256": {"scripts/"+name+".py": sha256(source_paths.source_project/"scripts"/(name+".py"))
                               for name in ("run_mn35k_acpf","run_mn35k_reactive_support")},
        "owned_code_sha256": inputs.owned_code_hashes(paths),
    }
    (tmp_path/"equivalence.json").write_text(json.dumps(report,indent=2)+"\n")


def compare_networks(left,right):
    assert left.meta==right.meta
    assert left.snapshots.equals(right.snapshots)
    for name in ("buses","lines","transformers","generators","loads","shunt_impedances","line_types","transformer_types"):
        pd.testing.assert_frame_equal(getattr(left,name),getattr(right,name),check_exact=True)
        if hasattr(left,name+"_t"):
            lt,rt=getattr(left,name+"_t"),getattr(right,name+"_t")
            assert set(lt)==set(rt)
            for field in lt:
                pd.testing.assert_frame_equal(lt[field],rt[field],check_exact=True,check_freq=False)
    # Actual engine Ybus, including the reactor, in the same bus ordering.
    for n in (left,right):
        n.calculate_dependent_values();n.determine_network_topology()
        for sn in n.sub_networks.obj:
            sn.find_bus_controls();sn.calculate_Y()
    for a,b in zip(left.sub_networks.obj,right.sub_networks.obj,strict=True):
        assert a.buses_o.equals(b.buses_o)
        assert np.array_equal(a.Y.toarray(),b.Y.toarray())


@pytest.mark.parametrize("module", [initial, reactive])
@pytest.mark.parametrize("unsafe", ["source","existing_dir","existing_file","symlink","hardlink","work","nested"])
def test_bad_destination(copied_inputs, module, unsafe):
    p=copied_inputs
    target=p.output_dir/"scenario"
    target.parent.mkdir(parents=True)
    if unsafe=="source": target=logical_input(p,"pypsa-earth/networks/MN_35k_poc/base.nc")
    elif unsafe=="existing_dir": target.mkdir()
    elif unsafe=="existing_file": target.write_text("unchanged")
    elif unsafe=="symlink": target.symlink_to(p.source_project,target_is_directory=True)
    elif unsafe=="hardlink": target.hardlink_to(logical_input(p,"pypsa-earth/networks/MN_35k_poc/base.nc"))
    elif unsafe=="work": target=p.work_dir/"scenario"
    else: p=replace(p,work_dir=p.output_dir/"nested")
    before=inputs.source_manifest(copied_inputs)
    with pytest.raises(ValueError): module.regenerate_for_verification(p,target)
    assert inputs.source_manifest(copied_inputs)==before


