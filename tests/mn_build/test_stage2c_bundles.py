@pytest.mark.parametrize("module",[initial,reactive])
@pytest.mark.parametrize("at",[3,5])
def test_partial_reports_never_published(source_paths,tmp_path,monkeypatch,module,at):
    p=replace(source_paths,output_dir=tmp_path/"generated")
    original=pd.DataFrame.to_csv
    count=0
    def failing(frame,*args,**kwargs):
        nonlocal count
        count+=1
        if count==at:raise OSError("injected report failure")
        return original(frame,*args,**kwargs)
    monkeypatch.setattr(pd.DataFrame,"to_csv",failing)
    target=p.output_dir/"scenario"
    with pytest.raises(OSError,match="injected"):module.regenerate_for_verification(p,target)
    assert not target.exists()
    assert list(p.output_dir.iterdir())==[]


