def test_failure_diagnostic_never_replaces_existing(source_paths,tmp_path,monkeypatch):
    p=replace(source_paths,output_dir=tmp_path/"generated")
    existing=p.output_dir/"scenario.failed";existing.mkdir(parents=True)
    sentinel=existing/"keep";sentinel.write_bytes(b"existing failure")
    def fail(*args):raise inputs.ScenarioFailure({"status":"AC_PF_NOT_CONVERGED"})
    monkeypatch.setattr(initial,"_generate",fail)
    with pytest.raises(ValueError,match="existing artifact"):
        initial.regenerate_for_verification(p,p.output_dir/"scenario")
    assert sentinel.read_bytes()==b"existing failure"
    assert not (p.output_dir/"scenario").exists()
